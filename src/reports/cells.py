"""Текст в ячейке выгрузки — всегда текст, а не формула.

Ячейка, начатая с `=`, `+`, `-`, `@`, табуляции или возврата каретки, в Excel и
его родне читается как формула. Текст в выгрузки приходит от людей и из
чужих файлов — причина отказа, название из выписки банка, назначение
платежа, — и «=HYPERLINK(...)» в нём сработало бы у того, кто откроет файл.
Такой текст отдаётся с апострофом впереди: таблица покажет его как есть.

Одно место на все выгрузки: правило, скопированное в каждую, разъезжается.
"""
from __future__ import annotations

FORMULA_START = ("=", "+", "-", "@", "\t", "\r")


def safe_cell(value):
    """Текст — безопасным текстом; числа, даты и пустое — как есть."""
    if isinstance(value, str) and value.startswith(FORMULA_START):
        return "'" + value
    return value
