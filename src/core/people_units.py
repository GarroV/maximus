"""Точки, между которыми делятся деньги человека, — пачкой на весь период (D055).

Кто спрашивает: табель и ведомость. Обоим нужен один и тот же ответ на весь
экран сразу, а не по человеку: людей три десятка, и запрос на каждого дал бы
столько же обращений к базе за тем же ответом.

**Границы периода читаются так же, как их читает расчёт** —
`payrun.posting._units_of`: полуоткрытый интервал `[valid_from, valid_to)` по
первому числу месяца. Второе прочтение тех же дат означало бы, что экран
показывает один набор точек, а деньги делятся по другому, — и разошлись бы они
молча.

**Через ORM, а не прямым SQL мимо политик.** На `employee_units` стоит срез по
точкам (`0267`), поэтому управляющий получает здесь только свои точки — он и не
должен узнать, где ещё работает его человек (D023). Запрос в обход политик
показал бы ему чужую точку на самом видном экране.
"""
from __future__ import annotations

from datetime import date
from uuid import UUID


def units_by_person(tenant_id: UUID, period: date) -> dict[UUID, tuple[str, ...]]:
    """`employee_id → коды точек`, действующие в этом периоде. Порядок — по коду.

    Человека, у которого привязок нет, в ответе нет вовсе: пустой набор означает
    «сеть», и отличить его от «не спрашивали» обязан тот, кто спрашивает.
    """
    from core.models import EmployeeUnit

    rows = (
        EmployeeUnit.objects.filter(tenant_id=tenant_id, valid_from__lte=period)
        .exclude(valid_to__lte=period)
        .select_related("unit")
        .values_list("employee_id", "unit__code")
    )
    found: dict[UUID, set] = {}
    for employee_id, code in rows:
        found.setdefault(employee_id, set()).add(code)
    return {employee_id: tuple(sorted(codes)) for employee_id, codes in found.items()}


def units_note(codes: tuple[str, ...], unit: str) -> str:
    """Подпись рядом с точкой строки: куда на самом деле идут деньги человека.

    Три случая, все три названы владельцем в D055:

    * точек несколько — деньги делятся между ними, и колонка с одной точкой без
      этой подписи говорила бы неправду;
    * точки нет ни в строке, ни в привязках — это офис, «вся сеть». Пустая
      ячейка читается как «данных нет», а не как «на всю сеть»;
    * точка одна — подписи нет: она повторяла бы саму колонку.

    Слова «Вся сеть» взяты те же, что у расхода юрлица: одно понятие — одно
    название, иначе на соседних экранах оно называлось бы по-разному.

    **Управляющему точки набор приходит уже урезанным** политикой `0267`: из
    двух точек своего человека он видит одну, набор схлопывается, и подписи не
    появляется. Так и надо — о существовании чужой точки он знать не должен
    (D023).
    """
    from django.utils.translation import gettext as _

    if len(codes) > 1:
        return _("делится: %(codes)s") % {"codes": ", ".join(codes)}
    if not codes and not unit:
        return _("Вся сеть")
    return ""
