"""Правило разнесения ФОТ сети, которое продукт поставляет сам (T221, D055).

Зарплата человека без точек — это офис: «офис на всех работает, вне
зависимости» (владелец, 27.08.2026), и такая сумма делится между всеми точками
поровну. Делает это общий механизм разнесения (`allocate_fact`), а он спрашивает
правило. У зарплатного факта нет ни контрагента, ни статьи расхода, поэтому
ключом служит сама строка P&L (`0270`).

**Почему правило не заводится у каждого партнёра.** Строка с пустым `tenant_id`
— та же конструкция, что у общего справочника строк P&L и системных ролей:
поставляется продуктом, видна каждому, правится только нами. Своё правило
партнёра перебивает общее. Заводись оно у каждого, его пришлось бы создавать в
каждом месте, где рождается партнёр, и четвёртый такой путь молча остался бы без
правила — а узналось бы это через месяц по висящей сумме.

**Почему рядом со справочником строк P&L, а не в миграции.** Сами строки
`labour_cost` и `payroll_taxes` заводит сид (у демо они называются
по-английски — демо всегда на английском), то есть на момент миграции их ещё нет
и привязывать правило не к чему. Миграция `0270` делает то же самое для тех
установок, где справочник уже заполнен; здесь — для тех, где он только
появляется. Обе стороны идемпотентны.
"""
from __future__ import annotations

from datetime import date

# Строки P&L, в которые ложится зарплата. Те же коды, что пишет перенос ФОТ в
# факты (`payrun.posting`): разъехавшись, правило перестало бы находиться, и
# ФОТ офиса снова повис бы неразнесённым.
PAYROLL_LINES = ("labour_cost", "payroll_taxes")

# Дата начала — заведомо раньше любых данных продукта: «поровну» не вводится с
# какого-то числа, это и есть поведение по умолчанию.
SINCE = date(2000, 1, 1)


def ensure_network_payroll_rules(items: dict) -> int:
    """Завести общее правило «поровну» для зарплатных строк P&L. Возвращает число новых.

    `items` — справочник строк P&L по коду, тот же, что вернул сид. Строки,
    которой нет, правило не получает: молча привязать зарплату к выдуманной
    строке хуже, чем не разнести.
    """
    from core.models import AllocationRule

    made = 0
    for code in PAYROLL_LINES:
        item = items.get(code)
        if item is None:
            continue
        exists = AllocationRule.objects.filter(
            tenant__isnull=True, pnl_item=item,
            counterparty__isnull=True, expense_item__isnull=True,
        ).exists()
        if exists:
            continue
        AllocationRule.objects.create(
            tenant=None, pnl_item=item, counterparty=None, expense_item=None,
            # Умолчание названо владельцем прямо. Второй способ («по выручке»)
            # уже существует у расходов и включится тем же полем, когда выручка
            # появится вместе с коннектором Dodo IS.
            method="even",
            ledger="official",
            valid_from=SINCE,
        )
        made += 1
    return made
