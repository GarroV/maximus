"""Сколько часов у человека за месяц — один ответ на весь продукт.

Правило простое, но ошибиться в нём легко дважды, и оба раза молча.

**Часы складываются все, без выбора «зачётных».** Вопрос, на который отвечает
этот модуль, — «сколько времени человек отдал работе», а не «что вошло в базу
для взносов»: для второго у табеля есть своя колонка `insured_hours`.

**Строк за месяц бывает две.** Перевод между точками посреди месяца даёт по
строке на точку, и взять первую значило бы показать половину месяца как весь
месяц. Часы при этом складываются, а норма — нет: норма календарная, одна на
месяц, поэтому берётся наибольшая. У полного месяца она у всех одна и та же, у
неполной строки бывает меньше.

Модуль появился, когда это правило нашлось написанным в третий раз (история
человека, печатная форма, сторож нормы окладника) — причём третья копия уже
ссылалась на первую комментарием «то же правило». Копия правила расходится с
оригиналом молча, и разойтись здесь означает показать разные часы одного
человека на двух экранах.
"""
from __future__ import annotations

from collections.abc import Iterable
from decimal import Decimal

__all__ = ["hours_of", "worked_and_norm"]


def hours_of(row) -> Decimal:
    """Часы одной строки табеля — все виды вместе."""
    return sum(
        (Decimal(str(value)) for value in (row.hours or {}).values()), Decimal(0)
    )


def worked_and_norm(rows: Iterable) -> tuple[Decimal, Decimal]:
    """Часы и норма по набору строк одного человека за один месяц."""
    worked = Decimal(0)
    norm = Decimal(0)
    for row in rows:
        worked += hours_of(row)
        norm = max(norm, row.norm_hours or Decimal(0))
    return worked, norm
