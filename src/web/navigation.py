"""Словарь разделов продукта — один на всё (issue #162, T194).

Модуль 10 эталона называет области учёта по работе человека, а не по механике
продукта: «Сбор данных», «Расчёт», «Отчёты», «Справочники», «Настройки», а
внутри — «Табель», «Наличные расходы», «Ведомость», «Закрытие месяца». У нас в
шапке стояли «Периоды · Расходы · Счета · Сотрудники»: слова про устройство
базы, а не про то, зачем человек пришёл. Владелец 18.08.2026 сказал ровно об
этом: «я не понимаю, как она работает, где какие функции».

**Зачем отдельный модуль.** Пока названия набраны прямо в шаблоне шапки, они не
сверяются ни с чем: расхождение с эталоном видно только тому, кто помнит обе
картинки целиком. Здесь словарь лежит один раз, а `tests/test_navigation_
dictionary.py` механически сверяет его со словами **из самого эталона** — не из
копии, переписанной в тест.

**Меню — только то, что человек может открыть (D100, #337).** До 12.11.2026
здесь стояли ВСЕ пункты эталона, включая ненаписанные (D064: «в демо нужны
вообще все экраны»), у чужой роли — пунктиром с предложением переключить роль
(T163), а «Счета» и три страницы аналитики — отдельными пунктами (D081, T224).
Разбор интерфейса 12.11.2026 (`docs/ux-review-2026-11-12.md`) насчитал 17 пунктов
у бухгалтера и 20 у управляющего, пункты с отказом за ними и заглушки.
Владелец: продукт должен быть удобным и лёгким к усвоению; образец — DECIMUS
(~11 пунктов в трёх группах). Поэтому:

* пункт виден, только если экран откроется: право пункта — то же, что
  проверяет сам экран (`SEES_SUMS` у ведомости, P&L, сверки и аналитики);
* ненаписанные экраны (`planned-*`) в продукте не показываются, в демо — тихо
  (`wip`); адреса-заглушки остаются;
* предложений «открыть другой ролью» нет — демо переключает роль кнопками на
  своей странице входа; группа без пунктов не рисуется нигде;
* «Входящие документы» — один раздел на очередь разбора, счета и бумаги с
  точек; «Аналитика по людям» — один пункт на три страницы со строкой ссылок.

Прежние решения D064, T163, D081 (в части состава меню) и T224 этим пересмотрены.
Как помечен ненаписанный экран в демо — по образцу DECIMUS (D098, #309): пункт
тише остальных и в подсказке «в разработке», без точек и плашек. Состояние
модулей живёт в `docs/product-map.md`.

**Где человек сейчас — по имени маршрута, а не по корню адреса** (#306). У
табеля, ведомости, закрытия, P&L и сверки общий корень `/periods/`, и по корню
подсвечивался всегда «Табель»: человек нажимал «Ведомость» и видел выделенным
другой пункт. Чей экран — решает `OWNER_OF_ROUTE`; для остальных маршрутов
корень адреса по-прежнему работает (`templatetags/ui.py`, `in_section`).

**Группы — подписями левой панели, а счётчик показывает ждущую работу**
(T222, D081). До 29.09.2026 область учёта была раскрывающимся меню в верхней
шапке (T207); владелец снял это дословно: «давай мы переведем навигацию в левую
сторону, как это сделано в наших других проектах. никаких выпадающих списков».
Меню, которое надо раскрыть, прячет разделы — человек не видит, что в системе
есть. Теперь все пункты видны сразу, область — подпись над своими пунктами. У
пункта стоит число работы, которая ждёт человека. Ноль не показывается вовсе:
это дословное правило эталона («Счётчик у пункта — это работа, которая ждёт
человека. Ноль не показываем»), и оно не про экономию места — ноль сообщает
«здесь есть очередь, и она пуста», а показывать надо обратное. Счётчик у
области, который был у раскрывающегося меню, снят: область больше не прячет
пункты, и число видно у самого пункта.

**Счётчик берётся из того же места, что и сам экран.** Не «похожим запросом», а
вызовом той же функции: два ответа на один вопрос расходятся молча — например,
когда политики базы сузят один не так, как другой, и человек увидит в панели
чужое число. Поэтому у пункта не «сколько-то там», а вызов источника его
собственного списка (`waiting=` у `Item`).
"""
