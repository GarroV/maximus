def is_open_to(item: Item, principal) -> bool:
    """Откроется ли экран пункта этому человеку — одно правило для меню и для
    `visible_for`. Право пункта берётся тем же, что проверяет сам экран (#337):
    пункт, за которым стоит отказ, в меню не рисуется."""
    from . import permissions

    codes = (item.needs,) if isinstance(item.needs, str) and item.needs else tuple(item.needs)
    if codes and not any(permissions.has(principal, code) for code in codes):
        return False
    return not (item.without and permissions.has(principal, item.without))


def is_planned(item: Item) -> bool:
    """Экрана ещё нет: в продукте пункт не показывается, в демо — тихо (D100)."""
    return item.route.startswith("planned-")


def visible_for(principal) -> list:
    """Пункты, которые видит этот человек. Порядок — эталонный.

    Право проверяется здесь, а не в шаблоне, по той же причине, по которой
    словарь лежит в модуле: правило видимости, размазанное по разметке, нельзя
    ни прочитать целиком, ни проверить. Срез ДАННЫХ при этом по-прежнему делает
    база (D014) — здесь решается только то, показывать ли ссылку.
    """
    from django.conf import settings

    demo = bool(getattr(settings, "DEMO_MODE", False))
    shown = []
    for group in GROUPS:
        for item in group.items:
            if is_planned(item) and not demo:
                continue
            if is_open_to(item, principal):
                shown.append(item)
    return shown


def sections(request) -> dict:
    """Области учёта для левой панели — контекст-процессором, а не в каждой вьюхе.

    Панель стоит на всех страницах, и собирать её в тридцати представлениях
    значило бы тридцать мест, где о новом разделе можно забыть.

    Что здесь решается и почему именно здесь:

    * **какие пункты человек ведёт** — правом, а не разметкой (см. `is_open_to`);
    * **сколько работы ждёт** — вызовом источника списка (`Item.waiting`), и
      только у пункта, который человек действительно ведёт: считать чужую
      очередь и не показывать её означало бы платить запросом за ничто;
    * **показывать ли область целиком.** Область, где нет ни одного своего
      пункта, не рисуется вовсе — ни в продукте, ни в демо: подпись группы над
      пустотой обещала бы раздел, которого у человека нет. Предложений «открыть
      другой ролью» (T163) больше нет: демо переключает роль кнопками на своей
      странице входа (D100).

    Где человек сейчас — поле `current` пункта (`_current`, #306): по имени
    маршрута для экранов внутри месяца, по корню адреса для остальных.
    """
    from django.conf import settings
    from django.urls import reverse

    from . import permissions
    from .principal import get_current_principal

    who = get_current_principal(request)
    # До входа разделов нет вовсе: каждый из них всё равно отвечает формой
    # входа, а гостю — это коллега, открывший рабочий продукт из хаба, — список
    # с точками очередей обещает то, что ему не откроется. Гайд и «Войти» стоят
    # в подвале панели и от этого не зависят.
    if who is None:
        return {"nav_areas": []}
    from core.spaces import is_platform_admin

    if request.path.startswith("/platform/") and is_platform_admin(who.user_id):
        items = []
        for route, title, icon in (
            ("platform-index", _("Пространства"), "home"),
            ("platform-users", _("Пользователи"), "team"),
            ("platform-history", _("Журнал изменений"), "timeline"),
            ("platform-settings", _("Настройки платформы"), "sliders"),
        ):
            url = reverse(route)
            current = "page" if request.path == url else ""
            if route == "platform-index" and not any(
                request.path.startswith(reverse(r)) for r in (
                    "platform-users", "platform-history", "platform-settings", "platform-rates",
                )
            ):
                current = current or "location"
            items.append({"url": url, "title": title, "icon": icon, "current": current,
                          "allowed": True, "route": route, "wip": False})
        areas = [{"number": 1, "title": _("Управление платформой"), "items": items}]
        return {"nav_areas": areas, "nav_tabs": _tabs(areas)}
    # Считать очередь есть смысл только у вошедшего: запрос в базу без
    # контекста партнёра ничего не значит.
    counting = who is not None and who.tenant_id is not None
    demo = bool(getattr(settings, "DEMO_MODE", False))
    owner = owner_of(request)
    path = request.path
    # Управляющий точки ведёт часы своей точки: «Табель» ведёт его сразу в
    # сетку рабочего месяца, минуя список месяцев и страницу расчёта (#315).
    unit_bound = bool(getattr(who, "unit_ids", None))

    areas = []
    for number, group in enumerate(GROUPS, start=1):
        items = []
        for item in group.items:
            # Пункт без экрана в продукте не рисуется вовсе, в демо — тихо.
            # Пункт, который человеку не откроется, не рисуется нигде: «открыть
            # другой ролью» демо даёт кнопками на странице входа (D100, #337).
            if (is_planned(item) and not demo) or not is_open_to(item, who):
                continue
            url = reverse(
                "timesheet-current" if unit_bound and item.route == "periods" else item.route
            )
            items.append({
                "title": item.title,
                "url": url,
                "route": item.route,
                "icon": item.icon,
                "allowed": True,
                # Экрана ещё нет — пункт тише остальных (как `is-wip` в DECIMUS).
                "wip": is_planned(item),
                "current": _current(item.route, url, owner, path),
                "waiting": (
                    item.waiting(who) if counting and item.waiting is not None else 0
                ),
            })

        # Область без своих пунктов не рисуется — ни в продукте, ни в демо.
        if not items:
            continue

        areas.append({
            "title": group.title,
            # Номер — для `id` подписи группы: список её пунктов ссылается на
            # подпись (`aria-labelledby`), и диктор называет группу, входя в неё.
            "number": number,
            "items": items,
        })
    if is_platform_admin(who.user_id):
        url = reverse("platform-index")
        areas.append({"number": len(GROUPS) + 1, "title": _("Управление платформой"),
                      "items": [{"title": _("Управление платформой"), "url": url,
                                 "route": "platform-index", "icon": "sliders",
                                 "allowed": True, "wip": False, "current": ""}]})
    return {"nav_areas": areas, "nav_tabs": _tabs(areas)}


def _current(route: str, url: str, owner: str, path: str) -> str:
    """Где человек относительно пункта: `page` — на нём самом, `location` —
    внутри его раздела, пусто — в другом месте.

    Различие как в DECIMUS: на самом экране пункт — не ссылка (переход в никуда),
    на вложенном — подсвеченная ссылка, которая ведёт в начало раздела.
    """
    if path == url:
        return "page"
    if owner:
        return "location" if owner == route else ""
    from .templatetags.ui import in_section

    return "location" if in_section(path, url) else ""


# Сколько пунктов помещается в нижнюю полосу телефона (как в DECIMUS, D518):
# больше — подписи режутся. Сверх пяти — четыре пункта и «Ещё» со списком.
TABBAR_MAX = 5


def _tabs(areas: list[dict]) -> dict:
    """Пункты нижней полосы телефона: основные и те, что под «Ещё».

    В полосу идут только разделы человека и только построенные: ненаписанный
    экран в пяти местах под большим пальцем занял бы место рабочего.
    """
    mine = [
        item for area in areas for item in area["items"]
        if item["allowed"] and not item["wip"]
    ]
    if len(mine) <= TABBAR_MAX:
        return {"main": mine, "more": [], "more_current": False}
    main, more = mine[:TABBAR_MAX - 1], mine[TABBAR_MAX - 1:]
    return {
        "main": main,
        "more": more,
        "more_current": any(item["current"] for item in more),
    }
