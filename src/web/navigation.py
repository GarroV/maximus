def visible_for(principal) -> list:
    """Пункты, которые видит этот человек. Порядок — эталонный.

    Право проверяется здесь, а не в шаблоне, по той же причине, по которой
    словарь лежит в модуле: правило видимости, размазанное по разметке, нельзя
    ни прочитать целиком, ни проверить. Срез ДАННЫХ при этом по-прежнему делает
    база (D014) — здесь решается только то, показывать ли ссылку.
    """
    from . import permissions

    shown = []
    for group in GROUPS:
        for item in group.items:
            if item.needs and not permissions.has(principal, item.needs):
                continue
            if item.without and permissions.has(principal, item.without):
                continue
            shown.append(item)
    return shown


def sections(request) -> dict:
    """Области учёта для левой панели — контекст-процессором, а не в каждой вьюхе.

    Панель стоит на всех страницах, и собирать её в тридцати представлениях
    значило бы тридцать мест, где о новом разделе можно забыть.

    Что здесь решается и почему именно здесь:

    * **какие пункты человек ведёт** — правом, а не разметкой (см. `visible_for`);
    * **сколько работы ждёт** — вызовом источника списка (`Item.waiting`), и
      только у пункта, который человек действительно ведёт: считать чужую
      очередь и не показывать её означало бы платить запросом за ничто;
    * **показывать ли область целиком.** Область, где нет ни одного своего
      пункта, в продукте не рисуется вовсе: подпись группы над пустотой обещала
      бы раздел, которого у человека нет. В демо она остаётся — там внутри
      стоит предложение открыть раздел подходящей ролью (T163), и без области
      оно было бы негде.

    Где человек сейчас, решает сам пункт (`components/sidenav_item.html`,
    фильтр `in_section`): области своей пометки больше не нужно — она не
    спрятана в меню, и открытый пункт виден внутри неё сразу.
    """
    from django.conf import settings
    from django.urls import reverse

    from . import permissions, stages
    from .principal import get_current_principal

    who = get_current_principal(request)
    # Считать очередь есть смысл только у вошедшего: до входа панель разделов не
    # показывает вовсе, а запрос в базу без контекста партнёра ничего не значит.
    counting = who is not None and who.tenant_id is not None
    demo = bool(getattr(settings, "DEMO_MODE", False))

    areas = []
    for number, group in enumerate(GROUPS, start=1):
        items = []
        for item in group.items:
            allowed = (
                (not item.needs or permissions.has(who, item.needs))
                and (not item.without or not permissions.has(who, item.without))
            )
            url = reverse(item.route)
            items.append({
                "title": item.title,
                "url": url,
                "needs": item.needs,
                "route": item.route,
                "icon": item.icon,
                "allowed": allowed,
                # Предложение переключить роль показывается только в демо и
                # только у раздела, который ведёт КОНКРЕТНОЕ право: у пункта без
                # права предлагать нечего (T163). Демо проверяется здесь, а не
                # одним тегом в разметке: в продукте тег отдаёт пустоту, и
                # панель получала бы пустой пункт списка, который диктор
                # объявляет пунктом без названия.
                "offer": demo and bool(item.needs) and not allowed,
                # Состояние — из `web.stages`, а не своим списком рядом: два
                # списка разъехались бы молча, и в меню стояла бы пометка,
                # которой на самом экране нет.
                "stage": stages.for_route(item.route),
                "waiting": (
                    item.waiting(who)
                    if allowed and counting and item.waiting is not None
                    else 0
                ),
            })

        mine = [item for item in items if item["allowed"]]
        offers = [item for item in items if item["offer"]]
        if not mine and not offers:
            continue

        areas.append({
            "title": group.title,
            # Номер — для `id` подписи группы: список её пунктов ссылается на
            # подпись (`aria-labelledby`), и диктор называет группу, входя в неё.
            "number": number,
            "items": items,
            # Чем заменить область, у которой человек не ведёт ни одного пункта:
            # в демо это ссылка «открыть ролью, которая её ведёт». Право и адрес
            # берутся у первого её пункта — предлагать сразу три способа войти в
            # одну область значило бы спрашивать посетителя о том, чего он ещё
            # не знает.
            "offer": None if mine else {
                "needs": offers[0]["needs"], "route": offers[0]["route"],
            },
        })
    return {"nav_areas": areas}

