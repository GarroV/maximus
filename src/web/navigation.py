def owner_of(request) -> str:
    """Имя маршрута пункта, чей это экран; пусто — решает корень адреса."""
    match = getattr(request, "resolver_match", None)
    name = getattr(match, "url_name", "") if match else ""
    return OWNER_OF_ROUTE.get(name or "", "")


def inbox_waiting(who) -> int:
    """Сколько работы ждёт в инбоксе — теми же выборками, что и его экран.

    Списка на экране два, и оба ждут одного человека: строки без статьи и
    бумаги, принесённые с точек (T174). Считать только первый значило бы
    показывать в шапке меньше, чем человек увидит, открыв раздел.

    Зовём **источники** обоих списков, а не пишем свой запрос: свой сузился бы
    иначе — например, мимо политик, которые режут строки по точке и регистру, —
    и число в шапке молча разошлось бы со списком. Считать по готовым строкам,
    а не `count()` по базе, здесь дешевле правильного: инбокс — очередь, которую
    человек разбирает руками, и длина у неё человеческая.
    """
    from . import papers, suppliers

    return (
        len(suppliers.waiting_for_an_article(who))
        + len(papers.papers(who, only_waiting=True))
    )


def statement_waiting(who) -> int:
    """Строки выписки, ждущие решения, — та же выборка, что у экрана."""
    from . import bank

    return bank.waiting_count(who)


@dataclass(frozen=True)
class Item:
    """Пункт навигации: имя из словаря, адрес и право, без которого его не видно."""

    title: object          # `gettext_lazy`, поэтому не `str`
    route: str             # имя маршрута Django
    # право; пусто — виден всем вошедшим. Кортеж — достаточно любого из прав
    # (так у аналитики: тот же список, что открывает экран, `SEES_SUMS`).
    needs: object = ""
    without: str = ""      # виден только тому, у кого этого права НЕТ
    # Чем считается ждущая работа: функция от человека, возвращающая число.
    # None — у пункта очереди нет, и счётчику взяться неоткуда.
    waiting: object = None
    # Значок из набора линейки (`static/web/icons.json`). Обязателен: от 720 до
    # 1099 пикселей панель сворачивается до значков (правило ядра), и пункт без
    # значка стал бы там пустой кнопкой.
    icon: str = "dots"


