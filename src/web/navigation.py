"""Словарь разделов продукта — один на всё (issue #162, T194).

Модуль 10 эталона называет области учёта по работе человека, а не по механике
продукта: «Сбор данных», «Расчёт», «Отчёты», «Справочники», «Настройки», а
внутри — «Табель», «Наличные расходы», «Ведомость», «Закрытие месяца». У нас в
шапке стояли «Периоды · Расходы · Счета · Сотрудники»: слова про устройство
базы, а не про то, зачем человек пришёл. Владелец 18.08.2026 сказал ровно об
этом: «я не понимаю, как она работает, где какие функции».

**Зачем отдельный модуль.** Пока названия набраны прямо в шаблоне шапки, они не
сверяются ни с чем: расхождение с эталоном видно только тому, кто помнит обе
картинки целиком. Здесь словарь лежит один раз, а `tests/test_navigation_
dictionary.py` механически сверяет его со словами **из самого эталона** — не из
копии, переписанной в тест.

**Здесь ВСЕ пункты словаря эталона, включая ненаписанные (D064).** Прежде было
наоборот — пунктов, которых в продукте нет, не рисовали: «пункт, ведущий в
никуда, хуже отсутствующего». Довод верен ровно про экран, который молчит.
Владелец 31.08.2026 закрыл развилку в другую сторону: «в демо нужны вообще все
экраны , те что сейчас в дработке - так и помечаем что В ДОРАБОТКЕ».

Цена прежнего правила выяснилась на показе: владелец открыл демо и решил, что
половины продукта нет, — при том что P&L, сверка и выгрузки были построены и
отвечали `200`, но в шапку не попали (#218). Скрытый пункт читается как
отсутствующий замысел, помеченный — как запланированная работа. Что помечено и
как — `web/stages.py`.

**Группы — подписями левой панели, а счётчик показывает ждущую работу**
(T222, D081). До 29.09.2026 область учёта была раскрывающимся меню в верхней
шапке (T207); владелец снял это дословно: «давай мы переведем навигацию в левую
сторону, как это сделано в наших других проектах. никаких выпадающих списков».
Меню, которое надо раскрыть, прячет разделы — человек не видит, что в системе
есть. Теперь все пункты видны сразу, область — подпись над своими пунктами. У
пункта стоит число работы, которая ждёт человека. Ноль не показывается вовсе:
это дословное правило эталона («Счётчик у пункта — это работа, которая ждёт
человека. Ноль не показываем»), и оно не про экономию места — ноль сообщает
«здесь есть очередь, и она пуста», а показывать надо обратное. Счётчик у
области, который был у раскрывающегося меню, снят: область больше не прячет
пункты, и число видно у самого пункта.

**Счётчик берётся из того же места, что и сам экран.** Не «похожим запросом», а
вызовом той же функции: два ответа на один вопрос расходятся молча — например,
когда политики базы сузят один не так, как другой, и человек увидит в панели
чужое число. Поэтому у пункта не «сколько-то там», а вызов источника его
собственного списка (`waiting=` у `Item`).
"""
from __future__ import annotations

from dataclasses import dataclass, field

from django.utils.translation import gettext_lazy as _

# Названия, которых в словаре эталона нет, и это осознанно. Каждое — с
# причиной: без причины список превращается в способ обойти сверку.
OUR_OWN = {
    # Роли и права: эталон рисует их страницей «Роли и права», а не пунктом
    # навигации (в его меню стоят «Доступы» — то же самое другими словами).
    # Наше имя оставлено, потому что оно совпадает с названием экрана, на
    # который ведёт, и с языком решений (D033, D052).
    "Роли и права",
}


def inbox_waiting(who) -> int:
    """Сколько работы ждёт в инбоксе — теми же выборками, что и его экран.

    Списка на экране два, и оба ждут одного человека: строки без статьи и
    бумаги, принесённые с точек (T174). Считать только первый значило бы
    показывать в шапке меньше, чем человек увидит, открыв раздел.

    Зовём **источники** обоих списков, а не пишем свой запрос: свой сузился бы
    иначе — например, мимо политик, которые режут строки по точке и регистру, —
    и число в шапке молча разошлось бы со списком. Считать по готовым строкам,
    а не `count()` по базе, здесь дешевле правильного: инбокс — очередь, которую
    человек разбирает руками, и длина у неё человеческая.
    """
    from . import papers, suppliers

    return (
        len(suppliers.waiting_for_an_article(who))
        + len(papers.papers(who, only_waiting=True))
    )


@dataclass(frozen=True)
class Item:
    """Пункт навигации: имя из словаря, адрес и право, без которого его не видно."""

    title: object          # `gettext_lazy`, поэтому не `str`
    route: str             # имя маршрута Django
    needs: str = ""        # право; пусто — виден всем вошедшим
    without: str = ""      # виден только тому, у кого этого права НЕТ
    # Чем считается ждущая работа: функция от человека, возвращающая число.
    # None — у пункта очереди нет, и счётчику взяться неоткуда.
    waiting: object = None
    # Значок из набора линейки (`static/web/icons.json`). Обязателен: от 720 до
    # 1099 пикселей панель сворачивается до значков (правило ядра), и пункт без
    # значка стал бы там пустой кнопкой.
    icon: str = "dots"


@dataclass(frozen=True)
class Group:
    """Область учёта эталона: «Сбор данных», «Расчёт», «Справочники»…"""

    title: object
    items: list = field(default_factory=list)


