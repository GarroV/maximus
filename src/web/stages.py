"""Экраны, которых ещё нет (D066, D098).

Каждый — пункт словаря навигации эталона (модуль 10). У пункта есть страница,
которая говорит, что здесь будет: скрытый пункт смотрящий читал как отсутствие
замысла (#218).

**Чего здесь больше нет.** До 27.10.2026 модуль вёл ещё и экраны «в доработке»:
плашка над экраном и цветная точка у пункта меню с фразой из журнала стройки —
«Разбор в две руки: директор разносит, бухгалтер подтверждает» и подобными.
Обход T240 показал, что бухгалтер читает это как поломку и не получает
подсказки, что делать (#309). Владелец 27.10.2026 велел привести каркас к
DECIMUS (D098), а там таких плашек нет: непостроенный раздел приглушён в меню, и
только. Поэтому состояние модулей (готов / доработка / ещё нет) живёт в одном
месте — `docs/product-map.md`, для владельца и стройки, а не для человека за
экраном.
"""
from __future__ import annotations

from dataclasses import dataclass

from django.utils.translation import gettext_lazy as _

__all__ = ["planned_screens"]


@dataclass(frozen=True)
class Planned:
    """Ненаписанный экран: заголовок, зачем он и когда его очередь."""

    code: str
    # Адрес — здесь, рядом с самим экраном, а не в `urls.py`: маршруты для этих
    # страниц собираются циклом по этому списку, и заводить экран в двух местах
    # значило бы однажды завести его в одном.
    url: str
    title: object
    what: object
    # Место в продуктовой карте. Человеку не показывается (#309): фраза про
    # очередь стройки ему ни о чём не говорит. Остаётся для тех, кто ведёт карту.
    when: object


PLANNED_SCREENS = [
    Planned(
        "payouts",
        "payouts/",
        _("Выплаты"),
        _("Что и когда ушло людям: ведомость к выплате, отметки о переводе, "
          "остаток задолженности по каждому человеку."),
        _("После того, как оплата труда закроется целиком"),
    ),
    Planned(
        "dodo-is",
        "settings/dodo-is/",
        _("Интеграция с Dodo IS"),
        _("Отработанные часы приезжают из Dodo IS вместо ручного ввода. "
          "Механизм подключения уже есть: каждый поток включается отдельно и "
          "по умолчанию выключен. Не хватает экрана и самого доступа к API."),
        _("Седьмая очередь; ждёт доступа к API Dodo IS"),
    ),
]

def planned_screens() -> list:
    """Ненаписанные экраны — для маршрутов и для навигации."""
    return list(PLANNED_SCREENS)
